// 从各平台保存的上游原图重新切图，并生成静态资源映射。
// node scripts/sync-appearance-assets.ts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const platforms = [
  ['Android', 'tools/slice-atlas.ts', 'app/src/main/res/drawable-nodpi'],
  ['Apple Platform', 'Tools/slice-atlas.ts', 'ComplexSweeper-Apple/Assets.xcassets'],
  ['HarmonyOS', 'scripts/atlas/slice.ts', 'entry/src/main/resources/base/media'],
];
for (const [platform, script, output] of platforms) {
  for (const [png, prefix] of [['atlas.png', 'cw_'], ['atlas-bw.png', 'cw_bw_']]) {
    const result = spawnSync(process.execPath, [script, 'assets/atlas.json', `assets/${png}`, output, prefix], {
      cwd: path.join(root, platform), stdio: 'inherit',
    });
    if (result.status !== 0) process.exit(result.status ?? 1);
  }
}
const iconJobs = [
  ['Android', 'tools/make-icon.ts', 'assets/atlas.json', 'assets/atlas.png', 'app/src/main/res'],
  ['Apple Platform', 'Tools/make-icon.ts', 'assets/atlas.json', 'assets/atlas.png', 'ComplexSweeper-Apple/Assets.xcassets'],
  ['HarmonyOS', 'scripts/atlas/make-icon.ts', 'entry/src/main/resources/base/media/cw_icon.png', 'AppScope/resources/base/media', 'entry/src/main/resources/base/media'],
];
for (const [platform, ...args] of iconJobs) {
  const result = spawnSync(process.execPath, args, { cwd: path.join(root, platform), stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
}
const slots = JSON.parse(fs.readFileSync(path.join(root, 'Android/assets/atlas.json'), 'utf8')).slots;
fs.writeFileSync(path.join(root, 'Android/app/src/main/java/top/rayawa/dashboard/complexsweeper/android/ui/AppearanceSprites.kt'),
  '// Generated by scripts/sync-appearance-assets.ts.\n' +
  'package top.rayawa.dashboard.complexsweeper.android.ui\n\n' +
  'import androidx.annotation.DrawableRes\nimport top.rayawa.dashboard.complexsweeper.android.R\n\n' +
  '@DrawableRes\ninternal fun monochromeSprite(@DrawableRes id: Int): Int = when (id) {\n' +
  slots.map((slot: { name: string }) => `    R.drawable.cw_${slot.name} -> R.drawable.cw_bw_${slot.name}`).join('\n') +
  '\n    else -> id\n}\n');
fs.writeFileSync(path.join(root, 'HarmonyOS/entry/src/main/ets/view/AppearanceSprites.ets'),
  '// Generated by scripts/sync-appearance-assets.ts.\n' +
  'export function colorSprite(source: Resource, colorEnabled: boolean): Resource {\n' +
  '  if (colorEnabled) return source;\n  switch (source.id) {\n' +
  slots.map((slot: { name: string }) => `    case $r('app.media.cw_${slot.name}').id: return $r('app.media.cw_bw_${slot.name}');`).join('\n') +
  '\n    default: return source;\n  }\n}\n');
